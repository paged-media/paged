// Bytes helpers of the public SDK. It cannot import the internal
// @paged-media/helpers (PM-0002), so it keeps its own copy, one per SDK.

/** Standard base64 of bytes (the SDK's one encoder: the data: URIs of
 *  `object-schema.ts` and the local image host's jobs). Chunked through `String.fromCharCode`, so a large
 *  image never exceeds the argument limit; `btoa` exists in every realm. */
export function toBase64(bytes: Uint8Array): string {
  let bin = "";
  for (let i = 0; i < bytes.length; i += 0x8000)
    bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(bin);
}
