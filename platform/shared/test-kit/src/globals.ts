// `stubGlobal` / `unstubAllGlobals`: vitest's `vi.stubGlobal` and
// `vi.unstubAllGlobals`, which bun:test's `vi` lacks. The first stub of a
// name remembers its original property descriptor; `unstubAllGlobals`
// puts every original back (or deletes a global that did not exist).

const originals = new Map<PropertyKey, PropertyDescriptor | undefined>();

export function stubGlobal(name: string | symbol, value: unknown): void {
  if (!originals.has(name)) originals.set(name, Object.getOwnPropertyDescriptor(globalThis, name));
  Object.defineProperty(globalThis, name, { value, writable: true, configurable: true, enumerable: true });
}

export function unstubAllGlobals(): void {
  for (const [name, descriptor] of originals) {
    if (descriptor) Object.defineProperty(globalThis, name, descriptor);
    else Reflect.deleteProperty(globalThis, name);
  }
  originals.clear();
}
