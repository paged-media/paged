/// A preset's cell; `None` for a name ECMA-376 does not define.
pub fn cell(preset: &str) -> Option<[u8; 8]> {
    CELLS.iter().find(|(n, _)| *n == preset).map(|(_, c)| *c)
}

/// The share of the cell the foreground covers (0–1); `None` for a name
/// ECMA-376 does not define.
pub fn coverage(preset: &str) -> Option<f64> {
    let c = cell(preset)?;
    Some(c.iter().map(|r| r.count_ones()).sum::<u32>() as f64 / 64.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_preset_has_a_cell_and_the_percentages_grow() {
        assert_eq!(CELLS.len(), 54);
        let pct: Vec<f64> = CELLS
            .iter()
            .filter(|(n, _)| n.starts_with("pct"))
            .map(|(n, _)| coverage(n).unwrap())
            .collect();
        assert_eq!(pct.len(), 12);
        assert!(pct.windows(2).all(|w| w[0] <= w[1]), "{pct:?}");
        assert_eq!(coverage("pct50"), Some(0.5));
        assert_eq!(coverage("horz"), Some(0.125));
        assert!(coverage("nope").is_none());
    }
}
