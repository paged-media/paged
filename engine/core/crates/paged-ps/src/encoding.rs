pub fn by_name(name: &str) -> Option<&'static [&'static str; 256]> {
    match name {
        "StandardEncoding" => Some(&STANDARD),
        "ISOLatin1Encoding" => Some(&ISO_LATIN1),
        _ => None,
    }
}

/// The character a glyph name stands for: the standard names, `uniXXXX`
/// and `uXXXX[XX]`, a name with a `.suffix` as its base.
pub fn unicode(name: &str) -> Option<char> {
    let base = name.split('.').next().unwrap_or(name);
    if let Ok(k) = UNICODE.binary_search_by(|(n, _)| (*n).cmp(base)) {
        return char::from_u32(UNICODE[k].1);
    }
    let hex = base
        .strip_prefix("uni")
        .filter(|h| h.len() == 4)
        .or_else(|| {
            base.strip_prefix('u')
                .filter(|h| (4..=6).contains(&h.len()))
        })?;
    char::from_u32(u32::from_str_radix(hex, 16).ok()?)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_and_names_agree() {
        assert_eq!(STANDARD[b'A' as usize], "A");
        assert_eq!(STANDARD[39], "quoteright");
        assert_eq!(STANDARD[0xE1], "AE");
        assert_eq!(ISO_LATIN1[0xE9], "eacute");
        assert_eq!(ISO_LATIN1[0xA0], "space");
        assert_eq!(unicode("eacute"), Some('\u{e9}'));
        assert_eq!(unicode("quoteright"), Some('\u{2019}'));
        assert_eq!(unicode("uni20AC"), Some('\u{20ac}'));
        assert_eq!(unicode("a.sc"), Some('a'));
        assert_eq!(unicode("zero"), Some('0'));
        assert!(UNICODE.windows(2).all(|w| w[0].0 < w[1].0), "sorted");
    }
}
