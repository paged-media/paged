// ORACLE PROBE -- DXF and SVG between paged.draw and Illustrator
// (draw ADR 364). GENERATED by packages/draw-bundle/test/oracle/
// gen-interchange-open.ts -- edit that, not this.
//
//   bash scripts/illustrator/run-probe.sh \
//     scripts/illustrator/probes/interchange-open.jsx \
//     packages/draw-bundle/test/fixtures/oracle/interchange-open.illustrator.json
//
// One synthetic drawing (a stroked rectangle, a stroked circle, a thick
// open cubic, a filled triangle), both ways:
//
//   svg-export        the SVG paged.draw's exporter writes for it (the
//                     engine's paged-svg), OPENED by Illustrator: its
//                     paths are copied into the scratch document at the
//                     same place relative to the artboard and measured.
//   illustrator-dxf   the drawing BUILT in Illustrator and EXPORTED as DXF
//                     (AutoCAD 2010, millimetres, true colours, maximum
//                     editability); the file's text is recorded, and the
//                     replay reads it with paged.draw's DXF importer.
//
// Why not "Illustrator opens paged.draw's DXF": opening (or placing) a
// DXF raises the DXF/DWG Options dialog, and a script cannot fill it in or
// keep it shut -- OpenOptionsAutoCAD has no constructor, app.open refuses
// the preference object (app.preferences.AutoCADFileOptions, "unknown open
// options"), a suppressed alert cancels the open ("the operation was
// cancelled"), and placedItems refuses the file. The exported DXF's own
// readability is pinned instead by the replay reading Illustrator's DXF
// and by draw-dxf's round trip.
//
// ASCII only (the runner refuses anything else).

(function () {
  function rgb(t) {
    var c = new RGBColor();
    c.red = t[0];
    c.green = t[1];
    c.blue = t[2];
    return c;
  }
  var K = 22.0914; // 0.5523 * 40: a quarter circle's handle
  var drawing = [
    PagedProbe.polygon([[20, 20], [120, 20], [120, 80], [20, 80]]),
    {
      closed: true,
      anchors: [
        { anchor: [240, 60], left: [240, 60 - K], right: [240, 60 + K] },
        { anchor: [200, 100], left: [200 + K, 100], right: [200 - K, 100] },
        { anchor: [160, 60], left: [160, 60 + K], right: [160, 60 - K] },
        { anchor: [200, 20], left: [200 - K, 20], right: [200 + K, 20] }
      ]
    },
    {
      closed: false,
      anchors: [
        { anchor: [20, 150], left: [20, 150], right: [60, 100] },
        { anchor: [160, 150], left: [120, 200], right: [160, 150] }
      ]
    },
    PagedProbe.polygon([[200, 120], [280, 120], [240, 190]])
  ];
  drawing[3].fill = [204, 51, 0];
  // Strokes of the first three paths, in paint order: [r, g, b, width].
  var strokes = [[255, 136, 0, 2], [0, 0, 255, 1], [0, 128, 0, 4]];

  var cases = [
    { id: "svg-export", input: { paths: [] }, parameters: { kind: "svg", text: "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"262pt\" height=\"183pt\" viewBox=\"18 19 262 183\">\n<path d=\"M20 20L120 20L120 80L20 80L20 20Z\" fill=\"none\" stroke=\"#ff8800\" stroke-width=\"2\"/>\n<path d=\"M240 60C240 82.091 222.091 100 200 100C177.909 100 160 82.091 160 60C160 37.909 177.909 20 200 20C222.091 20 240 37.909 240 60Z\" fill=\"none\" stroke=\"#0000ff\" stroke-width=\"1\"/>\n<path d=\"M20 150C60 100 120 200 160 150\" fill=\"none\" stroke=\"#008000\" stroke-width=\"4\"/>\n<path d=\"M200 120L280 120L240 190L200 120Z\" fill=\"#cc3300\"/>\n</svg>\n" } },
    {
      id: "illustrator-dxf",
      input: { paths: drawing },
      parameters: { kind: "dxf-export", strokes: strokes },
      allowUnchanged: true
    }
  ];

  function openSvg(doc, parameters, theCase) {
    var f = new File(Folder.temp + "/paged-interchange-" + theCase.id + ".svg");
    f.encoding = "UTF-8";
    f.lineFeed = "Unix";
    if (!f.open("w")) throw new Error("cannot write " + f.fsName);
    f.write(parameters.text);
    f.close();
    var opened = null;
    try {
      opened = app.open(f, DocumentColorSpace.RGB);
      var from = opened.artboards[0].artboardRect;
      var to = doc.artboards[0].artboardRect;
      var i, l, dup;
      for (l = 0; l < opened.layers.length; l++) {
        for (i = 0; i < opened.layers[l].pageItems.length; i++) {
          dup = opened.layers[l].pageItems[i].duplicate(doc.layers[0], ElementPlacement.PLACEATEND);
          dup.translate(to[0] - from[0], to[1] - from[1]);
        }
      }
      theCase.parameters.opened_artboard = [from[0], from[1], from[2], from[3]];
    } finally {
      if (opened !== null) opened.close(SaveOptions.DONOTSAVECHANGES);
      f.remove();
    }
  }

  function exportDxf(doc, items, parameters, theCase) {
    var i, s;
    for (i = 0; i < parameters.strokes.length; i++) {
      s = parameters.strokes[i];
      PagedProbe.setStroke(items[i], { width: s[3], cap: "butt", join: "miter", miterLimit: 4 });
      items[i].strokeColor = rgb([s[0], s[1], s[2]]);
    }
    var out = new File(Folder.temp + "/paged-interchange-" + theCase.id + ".dxf");
    var o = new ExportOptionsAutoCAD();
    o.exportFileFormat = AutoCADExportFileFormat.DXF;
    o.version = AutoCADCompatibility.AutoCADRelease24;
    o.unit = AutoCADUnit.Millimeters;
    o.unitScaleRatio = 1.0;
    o.colors = AutoCADColors.TrueColors;
    o.exportOption = AutoCADExportOption.MaximumEditability;
    o.exportSelectedArtOnly = false;
    o.alterPathsForAppearance = false;
    o.convertTextToOutlines = true;
    o.scaleLineweights = false;
    doc.exportFile(out, ExportType.AUTOCAD, o);
    try {
      out.encoding = "BINARY";
      if (!out.open("r")) throw new Error("cannot read " + out.fsName);
      theCase.parameters.illustrator_dxf = out.read();
      out.close();
    } finally {
      out.remove();
    }
  }

  return PagedProbe.run({
    probe: "interchange-open",
    operation:
      "svg-export: the SVG written to Folder.temp and app.open(file, RGB), every page item " +
      "duplicated into the scratch document, translated so the opened artboard's top-left " +
      "lands on the scratch artboard's, the opened document closed unsaved. " +
      "illustrator-dxf: the drawing built in the scratch document and doc.exportFile(file, " +
      "ExportType.AUTOCAD, ExportOptionsAutoCAD {DXF, AutoCAD 2010, millimetres, ratio 1, " +
      "true colours, maximum editability}), the file's text recorded",
    cases: cases,
    apply: function (doc, items, parameters, theCase) {
      if (parameters.kind === "svg") openSvg(doc, parameters, theCase);
      else exportDxf(doc, items, parameters, theCase);
    }
  });
})();
