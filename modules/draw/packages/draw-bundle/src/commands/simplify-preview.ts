// SIMPLIFY'S LIVE PREVIEW — what the Path Options panel's Simplify
// section draws over the canvas while its tolerance or corner angle is
// edited, before anything is written.
//
// WHAT IT DRAWS. Every selected path, simplified by draw-geometry's
// `simplifyAnchorTable` at the section's values and mapped to page space,
// as a DASHED cubic preview path per contour, plus the anchor counts
// before and after (the section shows them).
//
// HOW CLOSE IT IS TO WHAT APPLY WRITES. With a corner angle set, EXACT:
// Apply writes this very fit (`applySimplifyPath`'s corner lane). With
// no corner angle Apply runs the ENGINE's `simplifyPath` (RDP, then
// kurbo's `simplify_bezpath`), which this module cannot run without
// writing — no engine door simplifies without applying — so the preview
// is the same fit at the same tolerance: the same shape, not always the
// same anchor count. `SIMPLIFY_PREVIEW_ENGINE_NOTE` says so in the panel.
//
// WHERE IT DRAWS. A RETAINED overlay layer of the bundle's own
// (`overlay.layers@1`), so the active tool's preview slot cannot wipe it
// and it cannot wipe the tool's; on a host without layers, the multi-shape
// tool-preview slot (`setToolPreviews`).

import type {
  BundleHost,
  ElementId,
  OverlayLayer,
  ToolPreviewShape,
} from "@paged-media/plugin-api";
import { contourRanges, simplifyAnchorTable } from "@paged-media/draw-geometry";

import { anchorsToPage, readEditablePath, tableOfRead } from "./path-rewrite";
import { supportsPathOps } from "./path-ops";

export interface SimplifyPreviewOptions {
  tolerance: number;
  /** Degrees; 0 = none (the engine lane). */
  cornerAngle: number;
}

export interface SimplifyPreview {
  shapes: ToolPreviewShape[];
  /** Anchors before / after, summed over the selection. */
  before: number;
  after: number;
}

/** The preview of simplifying `targets` at `options`. Pure apart from the
 *  reads; unreadable targets are skipped. */
export async function simplifyPreviewOf(
  host: BundleHost,
  targets: readonly ElementId[],
  options: SimplifyPreviewOptions,
): Promise<SimplifyPreview> {
  const out: SimplifyPreview = { shapes: [], before: 0, after: 0 };
  const tolerance = Math.max(0, options.tolerance);
  for (const id of targets.filter(supportsPathOps)) {
    const read = await readEditablePath(host, id);
    if (!read || read.anchors.length < 3 || tolerance <= 0) continue;
    const pageId = read.pageId;
    if (!pageId) continue;
    const { table, matrix } = tableOfRead(read);
    const simplified = simplifyAnchorTable(table, {
      tolerance,
      cornerAngleDeg: Math.max(0, options.cornerAngle),
    });
    out.before += table.anchors.length;
    out.after += simplified.anchors.length;
    const ranges = contourRanges(
      simplified.anchors.length,
      simplified.subpathStarts,
    );
    ranges.forEach(([from, to], i) => {
      const open = simplified.subpathOpen?.[i] ?? false;
      out.shapes.push({
        pageId,
        anchors: anchorsToPage(simplified.anchors.slice(from, to), matrix),
        close: !open,
        dashed: true,
      });
    });
  }
  return out;
}

const layers = new WeakMap<BundleHost, OverlayLayer>();

/** Show `shapes` (null / empty clears). The layer is created on the
 *  first shapes it is given and its id is generated by the host — one
 *  bundle can be reached through several host wrappers, and a fixed id
 *  would collide between them. */
export function showSimplifyPreview(
  host: BundleHost,
  shapes: readonly ToolPreviewShape[] | null,
): void {
  const any = !!shapes && shapes.length > 0;
  if (host.supports("overlay.layers@1")) {
    let layer = layers.get(host);
    if (!layer) {
      if (!any) return;
      layer = host.overlay.layer();
      layers.set(host, layer);
    }
    if (any) layer.set(shapes!);
    else layer.clear();
    return;
  }
  host.overlay.setToolPreviews(any ? shapes : null);
}

/** Clear it. */
export function clearSimplifyPreview(host: BundleHost): void {
  showSimplifyPreview(host, null);
}
