// Writes src/show/shaders/sources.generated.ts: every *.wgsl in that
// directory as a string, so the transition renderer needs no bundler
// affordance (`?raw` works in Vite and the Bun runtime but not in
// `bun build`). Run after editing a shader:
//
//   bun run gen:shaders
//
// test/transitions.spec.ts fails while the generated module and the .wgsl
// files disagree.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const SHADER_DIR = resolve(
  import.meta.dir,
  "..",
  "src",
  "show",
  "shaders",
);
export const GENERATED = join(SHADER_DIR, "sources.generated.ts");

/** Every shader file's text by name (file name without `.wgsl`). */
export function readShaderFiles(dir = SHADER_DIR): Record<string, string> {
  const out: Record<string, string> = {};
  for (const f of readdirSync(dir).sort()) {
    if (f.endsWith(".wgsl"))
      out[f.slice(0, -5)] = readFileSync(join(dir, f), "utf8");
  }
  return out;
}

const HEADER =
  readFileSync(new URL(import.meta.url), "utf8").split("*/")[0] + "*/";

export function renderSourcesModule(files: Record<string, string>): string {
  const lines = [
    HEADER,
    "",
    "// GENERATED by scripts/gen-shaders.ts from the .wgsl files beside it.",
    "// Do not edit; run `bun run gen:shaders`.",
    "",
    "export const SHADER_SOURCES: Readonly<Record<string, string>> = {",
    ...Object.entries(files).map(
      ([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`,
    ),
    "};",
    "",
  ];
  return lines.join("\n");
}

/** The animation layer compositor's shaders (slide ADR 714), beside
 *  their own module. */
export const EFFECT_DIR = resolve(import.meta.dir, "..", "src", "show", "effects");
export const EFFECT_GENERATED = join(EFFECT_DIR, "sources.generated.ts");

export function renderEffectsModule(files: Record<string, string>): string {
  return renderSourcesModule(files).replace(
    "export const SHADER_SOURCES",
    "export const EFFECT_SOURCES",
  );
}

if (import.meta.main) {
  writeFileSync(GENERATED, renderSourcesModule(readShaderFiles()));
  console.log(`wrote ${GENERATED}`);
  writeFileSync(
    EFFECT_GENERATED,
    renderEffectsModule(readShaderFiles(EFFECT_DIR)),
  );
  console.log(`wrote ${EFFECT_GENERATED}`);
}
