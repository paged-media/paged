#!/usr/bin/env python3
# paged.sheet — Excel oracle ENTRY lane (what a typed cell entry stores).
#
# Usage:  sheet-conformance/oracle/excel/drive.sh --entry [locale]
#         (drives `entry.py build`, Excel, then `entry.py read`)
#
#   entry.py build <locale>        build/entry-<locale>.txt (one raw per line)
#   entry.py read <locale> <meta>  build/entry-<locale>.excel.xlsx + the
#                                  AppleScript's per-row report <meta>
#                                  -> recorded/entry[-<lang>].tsv
#
# Columns: id, raw, pre, type, value, numfmt, numfmt_id, quote
#   raw        the typed text (escaped \\ \t \n \r)
#   pre        the number format the cell had before the entry ("" = General)
#   type       n | s | b | e | f (a formula — value is its result) | blank
#   value      Excel's stored <v> VERBATIM (17-digit numbers)
#   numfmt     Excel's own `number format` of the cell after the entry
#   numfmt_id  the xlsx numFmtId of the cell's xf (builtin ids < 164)
#   quote      1 when Excel set the quote prefix (a leading `'`)

from __future__ import annotations

import datetime
import plistlib
import sys
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

import entry_cases as ec
import oracle_cases as oc
from read import M, esc, rich_errors, shared_strings, sheet_parts

LOCALES = {"en-US": ec.EN_US, **{loc: ec.locale_cases(loc) for loc in ec.LOCALE_SPELLING}}
EXCEL_APP = Path("/Applications/Microsoft Excel.app/Contents/Info.plist")


def cases(locale: str) -> list[tuple[str, str, str]]:
    """(id, raw, number format set before typing — "" for General)."""
    if locale not in LOCALES:
        raise SystemExit(f"no entry cases for {locale!r} (have {sorted(LOCALES)})")
    out = [(cid, raw, "") for cid, raw in LOCALES[locale]]
    if locale == "en-US":
        out += ec.PREFORMATTED
    return out


def build(locale: str) -> Path:
    path = oc.build_dir() / f"entry-{locale}.txt"
    lines = []
    for _, raw, fmt in cases(locale):
        if any(ch in raw + fmt for ch in "\t\r\n"):
            raise SystemExit(f"entry raw {raw!r} / {fmt!r} has a tab or line break")
        lines.append(f"{fmt}\t{raw}")
    path.write_text("\n".join(lines), encoding="utf-8")  # no trailing newline
    print(path)
    return path


def excel_build() -> str:
    try:
        info = plistlib.loads(EXCEL_APP.read_bytes())
        return f"{info['CFBundleShortVersionString']} ({info['CFBundleVersion']})"
    except (OSError, KeyError, plistlib.InvalidFileException):
        return "unknown"


def xf_formats(z: zipfile.ZipFile) -> tuple[list[int], list[bool]]:
    """cellXfs index -> (numFmtId, quotePrefix)."""
    root = ET.fromstring(z.read("xl/styles.xml"))
    xfs = root.find(f"{M}cellXfs")
    ids, quotes = [], []
    for xf in xfs.findall(f"{M}xf") if xfs is not None else []:
        ids.append(int(xf.get("numFmtId", "0")))
        quotes.append(xf.get("quotePrefix") in ("1", "true"))
    return ids, quotes


def read(locale: str, meta_path: str) -> int:
    rows_in = cases(locale)
    src = oc.build_dir() / f"entry-{locale}.excel.xlsx"
    if not src.exists():
        raise SystemExit(f"{src} missing — run drive.sh --entry first")
    meta: dict[int, tuple[str, str]] = {}
    for line in Path(meta_path).read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        if line.startswith("ERR"):
            raise SystemExit(f"Excel reported: {line}")
        n, fmt, prefix = (line.split("\t") + ["", ""])[:3]
        meta[int(n)] = (fmt, prefix)
    if len(meta) != len(rows_in):
        raise SystemExit(f"{len(meta)} meta rows for {len(rows_in)} inputs")
    with zipfile.ZipFile(src) as z:
        sst = shared_strings(z)
        rich = rich_errors(z)
        part = next(iter(sheet_parts(z).values()))
        fmt_ids, quotes = xf_formats(z)
        cells = {c.get("r"): c for c in ET.fromstring(z.read(part)).iter(f"{M}c")}
        out = [
            "# Excel-recorded typed cell entry (generated by oracle/excel/entry.py — do not hand-edit)",
            f"# excel: Microsoft Excel {excel_build()}; locale: {locale}; "
            f"recorded: {datetime.date.today().isoformat()}",
            "# id\traw\tpre\ttype\tvalue\tnumfmt\tnumfmt_id\tquote",
        ]
        for n, (cid, raw, pre) in enumerate(rows_in, 1):
            c = cells.get(f"A{n}")
            t, v, xf = "blank", "", 0
            if c is not None:
                xf = int(c.get("s", "0"))
                tt = c.get("t", "n")
                ve = c.find(f"{M}v")
                text = (ve.text or "") if ve is not None else ""
                if c.find(f"{M}f") is not None:
                    t, v = "f", text
                elif tt == "s":
                    t, v = "s", sst[int(text)]
                elif tt == "inlineStr":
                    t, v = "s", "".join(x.text or "" for x in c.iter(f"{M}t"))
                elif tt == "str":
                    t, v = "s", text
                elif tt == "e" and c.get("vm") and int(c.get("vm")) in rich:
                    t, v = "e", rich[int(c.get("vm"))]
                elif ve is None:
                    t, v = "blank", ""
                else:
                    t, v = tt, text
            fmt, prefix = meta[n]
            fid = fmt_ids[xf] if xf < len(fmt_ids) else 0
            quote = "1" if (xf < len(quotes) and quotes[xf]) or prefix == "'" else "0"
            out.append("\t".join([cid, esc(raw), esc(pre), t, esc(v), esc(fmt), str(fid), quote]))
    lang = locale.split("-")[0]
    name = "entry.tsv" if locale == "en-US" else f"entry-{lang}.tsv"
    dst = oc.oracle_dir() / "recorded" / name
    dst.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"entry {locale}: recorded {len(rows_in)} case(s) -> {dst.name}")
    return 0


def main(argv: list[str]) -> int:
    if len(argv) >= 2 and argv[0] == "build":
        build(argv[1])
        return 0
    if len(argv) >= 3 and argv[0] == "read":
        return read(argv[1], argv[2])
    raise SystemExit("usage: entry.py build <locale> | read <locale> <meta>")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
